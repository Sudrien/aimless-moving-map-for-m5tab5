static void aes_expand(const uint8_t k[16], uint8_t rk[176]) {
    memcpy(rk, k, 16);
    for (int i = 16; i < 176; i += 4) {
        uint8_t t[4] = { rk[i-4], rk[i-3], rk[i-2], rk[i-1] };
        if (i % 16 == 0) {
            uint8_t tmp = t[0];
            t[0] = AES_SB[t[1]] ^ AES_RCON[i/16];
            t[1] = AES_SB[t[2]]; t[2] = AES_SB[t[3]]; t[3] = AES_SB[tmp];
        }
        for (int j = 0; j < 4; j++) rk[i+j] = rk[i-16+j] ^ t[j];
    }
}
static void aes_inv_shiftrows(uint8_t s[16]) {
    uint8_t t;
    t = s[13]; s[13]=s[9]; s[9]=s[5]; s[5]=s[1]; s[1]=t;
    t = s[2]; s[2]=s[10]; s[10]=t; t=s[6]; s[6]=s[14]; s[14]=t;
    t = s[3]; s[3]=s[7]; s[7]=s[11]; s[11]=s[15]; s[15]=t;
}
static void aes_dec_block(const uint8_t rk[176], const uint8_t in[16], uint8_t out[16]) {
    uint8_t s[16]; memcpy(s, in, 16);
    for (int j = 0; j < 16; j++) s[j] ^= rk[160+j];
    for (int round = 9; round >= 1; round--) {
        aes_inv_shiftrows(s);
        for (int j = 0; j < 16; j++) s[j] = AES_ISB[s[j]];
        for (int j = 0; j < 16; j++) s[j] ^= rk[round*16+j];
        for (int c = 0; c < 4; c++) {                 /* InvMixColumns via tables */
            uint8_t *q = s + c*4, a0=q[0], a1=q[1], a2=q[2], a3=q[3];
            q[0] = AES_M14[a0]^AES_M11[a1]^AES_M13[a2]^AES_M9[a3];
            q[1] = AES_M9[a0]^AES_M14[a1]^AES_M11[a2]^AES_M13[a3];
            q[2] = AES_M13[a0]^AES_M9[a1]^AES_M14[a2]^AES_M11[a3];
            q[3] = AES_M11[a0]^AES_M13[a1]^AES_M9[a2]^AES_M14[a3];
        }
    }
    aes_inv_shiftrows(s);
    for (int j = 0; j < 16; j++) s[j] = AES_ISB[s[j]];
    for (int j = 0; j < 16; j++) s[j] ^= rk[j];
    memcpy(out, s, 16);
}
/* AES-128-CBC decrypt in place of mbedtls_aes_crypt_cbc. */
static void aes128_cbc_decrypt(const uint8_t key[16], const uint8_t iv[16],
                               const uint8_t *in, size_t n, uint8_t *out) {
    uint8_t rk[176]; aes_expand(key, rk);
    uint8_t prev[16]; memcpy(prev, iv, 16);
    for (size_t off = 0; off < n; off += 16) {
        uint8_t blk[16]; aes_dec_block(rk, in + off, blk);
        for (int j = 0; j < 16; j++) out[off+j] = blk[j] ^ prev[j];
        memcpy(prev, in + off, 16);
    }
}
/* ---- base64 ------------------------------------------------------------- */

int lkey_b64_decode(const char *s, uint8_t *o, size_t cap)
{
    int8_t t[256];
    memset(t, -1, sizeof(t));
    static const char A[] = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    for (int i = 0; i < 64; i++) t[(uint8_t)A[i]] = (int8_t)i;
    size_t n = 0;
    int acc = 0, bits = 0;
    for (const char *p = s; *p && *p != '='; p++) {
        const int v = t[(uint8_t)*p];
        if (v < 0) continue;                 /* whitespace, newlines */
        acc = ((acc << 6) | v) & 0xFFFFFF;
        bits += 6;
        if (bits >= 8) {
            bits -= 8;
            if (n >= cap) return -1;
            o[n++] = (uint8_t)((acc >> bits) & 0xff);
        }
    }
    return (int)n;
}

/* ---- the key ------------------------------------------------------------ */

void lkey_build_key(const uint8_t *raw, size_t len, uint8_t key[16])
{
    if (len == 0) { memset(key, 0, 16); return; }
    for (int i = 0; i < 16; i++) key[i] = raw[i % len];
}

int lkey_decrypt(const uint8_t key[16], const uint8_t *ct, size_t ct_len,
                 uint8_t *out, size_t out_cap)
{
    if (ct_len == 0 || ct_len % 16 || ct_len + 1 > out_cap) return -1;
    aes128_cbc_decrypt(key, LI_IV, ct, ct_len, out);
    const int pad = out[ct_len - 1];
    if (pad < 1 || pad > 16 || (size_t)pad > ct_len) return -1;
    for (int i = 0; i < pad; i++) if (out[ct_len - 1 - i] != pad) return -1;
    const int plen = (int)ct_len - pad;
    if (plen < 1) return -1;
    for (int i = 0; i < plen; i++) if (out[i] < 0x20 || out[i] > 0x7e) return -1;
    out[plen] = 0;
    return plen;
}

bool lkey_oracle_add(lkey_oracle_t *o, const char *b64)
{
    if (o->n >= 2 || !b64 || !b64[0]) return false;
    const int n = lkey_b64_decode(b64, o->ct[o->n], sizeof(o->ct[0]));
    if (n <= 0 || n % 16) return false;
    o->len[o->n] = (size_t)n;
    o->n++;
    return true;
}

bool lkey_key_ok(const uint8_t key[16], const lkey_oracle_t *o)
{
    uint8_t tmp[LKEY_CT_MAX + 1];
    if (o->n < 1) return false;
    const int l0 = lkey_decrypt(key, o->ct[0], o->len[0], tmp, sizeof(tmp));
    if (l0 < 0) return false;
    if (o->n >= 2) return lkey_decrypt(key, o->ct[1], o->len[1], tmp, sizeof(tmp)) >= 0;
    return l0 >= 8;   /* one ciphertext: lean on WPA's 8-character floor */
}

/* ---- the scan ----------------------------------------------------------- */

void lkey_scan_init(lkey_scan_t *s, const lkey_oracle_t *o)
{
    memset(s, 0, sizeof(*s));
    s->o = o;
}

/* Every suffix of the run at least LKEY_MIN_CAND long, longest first. */
static void flush(lkey_scan_t *s)
{
    if (s->rl >= LKEY_MIN_CAND) {
        for (size_t k = 0; k + LKEY_MIN_CAND <= s->rl && !s->found; k++) {
            uint8_t key[16];
            lkey_build_key(s->run + k, s->rl - k, key);
            if (lkey_key_ok(key, s->o)) {
                memcpy(s->key, key, 16);
                s->found = true;
            }
        }
    }
    s->rl = 0;
}

bool lkey_scan(lkey_scan_t *s, const uint8_t *buf, size_t n)
{
    for (size_t i = 0; i < n && !s->found; i++) {
        const uint8_t b = buf[i];
        const bool pr = (b >= 0x20 && b <= 0x7e);
        if (pr && s->rl < LKEY_MAX_CAND) {
            s->run[s->rl++] = b;
            continue;
        }
        flush(s);
        if (pr) s->run[s->rl++] = b;
    }
    return s->found;
}

bool lkey_scan_end(lkey_scan_t *s)
{
    if (!s->found) flush(s);
    return s->found;
}

/* ---- what a value is ---------------------------------------------------- */

bool lkey_classify(const char *s, bool *is_psk)
{
    const size_t n = strlen(s);
    *is_psk = false;
    if (n == 64) {
        for (size_t i = 0; i < 64; i++) {
            const char c = s[i];
            const bool hex = (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') ||
                             (c >= 'A' && c <= 'F');
            if (!hex) return false;
        }
        *is_psk = true;
        return true;
    }
    return n >= 8 && n <= 63;
}
